#!/usr/bin/env python3
"""Vendor the reviewed Lucide subset from a pinned upstream commit. No npm/runtime JS."""
from concurrent.futures import ThreadPoolExecutor
from hashlib import sha256
from pathlib import Path
import argparse
import json
import urllib.request
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[2]
CONFIG = json.loads(Path(__file__).with_name("lucide.json").read_text())
BASE = f"https://raw.githubusercontent.com/lucide-icons/lucide/{CONFIG['commit']}/"
DEST = ROOT / "src/PlaceContext.Host/wwwroot/vendor"
NS = "http://www.w3.org/2000/svg"
ET.register_namespace("", NS)


def fetch(path):
    with urllib.request.urlopen(BASE + path, timeout=30) as response:
        return response.read()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify committed assets without writing")
    args = parser.parse_args()
    aliases = CONFIG["aliases"]
    names = sorted(set(aliases.values()))
    with ThreadPoolExecutor(max_workers=8) as pool:
        raw_icons = dict(zip(names, pool.map(lambda name: fetch(f"icons/{name}.svg"), names)))
    license_data = fetch("LICENSE")
    sprite = ET.Element(f"{{{NS}}}svg")
    sources = {}
    allowed = {"path", "rect", "circle", "ellipse", "line", "polyline", "polygon"}
    for name, raw in raw_icons.items():
        icon = ET.fromstring(raw)
        assert icon.get("viewBox") == "0 0 24 24", name
        assert icon.get("stroke-width") == "2", name
        symbol = ET.SubElement(sprite, f"{{{NS}}}symbol", {"id": name, "viewBox": "0 0 24 24"})
        for child in icon:
            assert child.tag.removeprefix(f"{{{NS}}}") in allowed, name
            assert not any(key.startswith("on") or key in {"href", "style"} for key in child.attrib), name
            child.tail = None
            symbol.append(child)
        sources[name] = {"path": f"icons/{name}.svg", "sha256": sha256(raw).hexdigest()}
    ET.indent(sprite, space="  ")
    sprite_data = (ET.tostring(sprite, encoding="unicode") + "\n").encode()
    asset_name = f"lucide-{CONFIG['version']}.svg"
    manifest = {
        "library": "Lucide", "version": CONFIG["version"], "commit": CONFIG["commit"],
        "source": "https://github.com/lucide-icons/lucide", "asset": asset_name,
        "sha256": sha256(sprite_data).hexdigest(), "license_sha256": sha256(license_data).hexdigest(),
        "icons": sources,
    }
    mappings = dict(aliases)
    mappings.update({name: name for name in names})
    rows = "\n".join(f'            ["{alias}"] = "{name}",' for alias, name in sorted(mappings.items()))
    catalog = '''// Generated by tools/icons/vendor_lucide.py from the pinned Lucide SVG sources.
// Update tools/icons/lucide.json and rerun the script; do not hand-draw icons here.
using System.Collections.Frozen;
using System.Globalization;
using System.Net;

namespace PlaceContext.Host.Components.ViewModels;

internal static class MainLayoutIconCatalog
{
    public const string SpritePath = "/vendor/ASSET_NAME";
    private static readonly FrozenDictionary<string, string> Icons =
        new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
        {
ROWS
        }.ToFrozenDictionary(StringComparer.OrdinalIgnoreCase);

    public static bool IsKnown(string? kind) => kind is not null && Icons.ContainsKey(kind.Trim());
    public static string Resolve(string? kind) => kind is not null && Icons.TryGetValue(kind.Trim(), out var name)
        ? name : "circle-question-mark";

    public static string Markup(string? kind, int size = 16, string cssClass = "nav-icon")
    {
        var name = Resolve(kind);
        var pixels = Math.Clamp(size, 8, 128).ToString(CultureInfo.InvariantCulture);
        var classes = WebUtility.HtmlEncode(cssClass);
        return $"<svg class='{classes} lucide-icon' data-icon='{name}' width='{pixels}' height='{pixels}' viewBox='0 0 24 24' fill='none' stroke='currentColor' stroke-width='2' stroke-linecap='round' stroke-linejoin='round' aria-hidden='true' focusable='false'><use href='{SpritePath}#{name}' /></svg>";
    }
}
'''.replace("ASSET_NAME", asset_name).replace("ROWS", rows)
    outputs = {
        DEST / asset_name: sprite_data,
        DEST / "lucide-LICENSE.txt": license_data,
        DEST / "lucide-manifest.json": (json.dumps(manifest, indent=2) + "\n").encode(),
        ROOT / "src/PlaceContext.Host/Components/ViewModels/MainLayoutIconCatalog.cs": catalog.encode(),
    }
    for path, data in outputs.items():
        if args.check:
            assert path.read_bytes() == data, f"Asset differs: {path.relative_to(ROOT)}"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(f"{'Verified' if args.check else 'Vendored'} {len(names)} Lucide {CONFIG['version']} icons; {len(mappings)} supported names.")


if __name__ == "__main__":
    main()
